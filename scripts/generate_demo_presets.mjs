import { readFile, writeFile } from "node:fs/promises";
import { presets, presetConfig } from "../software/smartknob-demo/src/presets.js";

const output = new URL("../firmware/src/demo/presets_generated.h", import.meta.url);
const labels = ["Free", "Coarse", "Fine", "Limit", "Switch", "Spring", "Heavy", "Magnet"];
const float = (n) => `${Number.isInteger(n) ? `${n}.0` : n.toPrecision(10)}f`;
const configFields = (c) => [
  c.position, float(c.subPositionUnit), 0, c.minPosition, c.maxPosition,
  float(c.positionWidthRadians), float(c.detentStrengthUnit), float(c.endstopStrengthUnit),
  float(c.snapPoint), JSON.stringify(c.text), c.detentPositions.length,
  `{${c.detentPositions.join(", ")}}`, float(c.snapPointBias), c.ledHue,
].join(", ");
const entries = presets.map((p, index) => {
  const variants = [0, 1].map((v) => {
    const c = presetConfig(p, 0, p.variants ? v : 0);
    c.text = `demo:${p.id}:${p.variants ? v : 0}`;
    return `        {${configFields(c)}}`;
  });
  return `    {${JSON.stringify(p.id)}, ${JSON.stringify(labels[index])}, ${p.ticks}, ${p.variants ? 2 : 1}, {\n${variants.join(",\n")}\n    }}`;
});
const content = `// Generated by node scripts/generate_demo_presets.mjs; do not edit.\n// Source: software/smartknob-demo/src/presets.js and feel.js.\n#pragma once\n\nstatic const DemoPreset kDemoPresets[] = {\n${entries.join(",\n")}\n};\n`;
if (process.argv.includes("--check")) {
  if (await readFile(output, "utf8") !== content) {
    throw new Error("Firmware presets differ from the Web demo. Run node scripts/generate_demo_presets.mjs.");
  }
  console.log("All 8 firmware presets and their variants match the Web demo.");
} else {
  await writeFile(output, content);
  console.log("Generated 8 firmware presets from the Web demo.");
}
